create table if not exists public.staff (
  telegram_id bigint primary key,
  username text,
  display_name text,
  role text not null default 'operator' check (role in ('operator', 'senior')),
  added_by bigint not null,
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  username text,
  display_name text not null default 'Без имени',
  status text not null default 'open' check (status in ('open', 'closed')),
  assigned_to bigint,
  created_at timestamptz not null default now(),
  closed_at timestamptz
);
create index if not exists tickets_user_status_idx on public.tickets(user_id, status);
create index if not exists tickets_status_idx on public.tickets(status);

create table if not exists public.ticket_messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(id) on delete cascade,
  sender_id bigint not null,
  sender_role text not null check (sender_role in ('user', 'staff', 'system')),
  message_type text not null default 'message',
  created_at timestamptz not null default now()
);
create index if not exists ticket_messages_ticket_idx on public.ticket_messages(ticket_id, created_at);

create table if not exists public.staff_sessions (
  staff_id bigint primary key,
  ticket_id bigint not null references public.tickets(id) on delete cascade,
  updated_at timestamptz not null default now()
);

alter table public.staff enable row level security;
alter table public.tickets enable row level security;
alter table public.ticket_messages enable row level security;
alter table public.staff_sessions enable row level security;
